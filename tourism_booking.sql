-- Requires Oracle Database 12c or newer. Run with F5 in SQL Developer, connected to Oracle.
-- The setup below makes rerunning the demo safe by removing its prior objects.
BEGIN
    FOR obj IN (
        SELECT object_name, object_type
          FROM user_objects
         WHERE object_name IN (
             'TOURISM_MANAGER_PKG',
             'LOG_SYSTEM_EVENT',
             'PAYMENTS',
             'BOOKINGS',
             'TRAVEL_PACKAGES',
             'DESTINATIONS',
             'USERS',
             'SYSTEM_AUDIT_LOGS'
         )
         ORDER BY CASE object_type
                      WHEN 'PACKAGE' THEN 1
                      WHEN 'PROCEDURE' THEN 2
                      WHEN 'TABLE' THEN 3
                      ELSE 4
                  END
    ) LOOP
        IF obj.object_type = 'PACKAGE' THEN
            EXECUTE IMMEDIATE 'DROP PACKAGE ' || obj.object_name;
        ELSIF obj.object_type = 'PROCEDURE' THEN
            EXECUTE IMMEDIATE 'DROP PROCEDURE ' || obj.object_name;
        ELSIF obj.object_type = 'TABLE' THEN
            EXECUTE IMMEDIATE 'DROP TABLE ' || obj.object_name || ' CASCADE CONSTRAINTS PURGE';
        END IF;
    END LOOP;
END;
/

CREATE TABLE Users (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name       VARCHAR2(150) NOT NULL,
    email           VARCHAR2(254) NOT NULL,
    phone           VARCHAR2(30),
    user_role       VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    account_status  VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (user_role IN ('CUSTOMER', 'AGENT', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

CREATE TABLE Destinations (
    destination_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    destination_name VARCHAR2(150) NOT NULL,
    country         VARCHAR2(100) NOT NULL,
    description     VARCHAR2(1000),
    base_cost       NUMBER(12, 2) DEFAULT 0 NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_destinations PRIMARY KEY (destination_id),
    CONSTRAINT uq_destinations_name_country UNIQUE (destination_name, country),
    CONSTRAINT ck_destinations_base_cost CHECK (base_cost >= 0)
);

CREATE TABLE Travel_Packages (
    package_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    destination_id  NUMBER NOT NULL,
    package_name    VARCHAR2(150) NOT NULL,
    duration_days   NUMBER(4) NOT NULL,
    price           NUMBER(12, 2) NOT NULL,
    capacity        NUMBER(8) NOT NULL,
    package_status  VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_travel_packages PRIMARY KEY (package_id),
    CONSTRAINT fk_packages_destination FOREIGN KEY (destination_id)
        REFERENCES Destinations (destination_id),
    CONSTRAINT uq_packages_destination_name UNIQUE (destination_id, package_name),
    CONSTRAINT ck_packages_duration CHECK (duration_days > 0),
    CONSTRAINT ck_packages_price CHECK (price >= 0),
    CONSTRAINT ck_packages_capacity CHECK (capacity > 0),
    CONSTRAINT ck_packages_status CHECK (package_status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE Bookings (
    booking_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id     NUMBER NOT NULL,
    package_id      NUMBER NOT NULL,
    travelers_count NUMBER(4) DEFAULT 1 NOT NULL,
    booking_date    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    status          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT pk_bookings PRIMARY KEY (booking_id),
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id)
        REFERENCES Users (user_id),
    CONSTRAINT fk_bookings_package FOREIGN KEY (package_id)
        REFERENCES Travel_Packages (package_id),
    CONSTRAINT ck_bookings_travelers CHECK (travelers_count > 0),
    CONSTRAINT ck_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);

CREATE TABLE Payments (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    booking_id      NUMBER NOT NULL,
    amount          NUMBER(12, 2) NOT NULL,
    payment_date    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    payment_method  VARCHAR2(30) NOT NULL,
    payment_status  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    transaction_ref VARCHAR2(100),
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id)
        REFERENCES Bookings (booking_id),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method CHECK (
        payment_method IN ('CARD', 'BANK_TRANSFER', 'CASH', 'WALLET')
    ),
    CONSTRAINT ck_payments_status CHECK (
        payment_status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED')
    ),
    CONSTRAINT uq_payments_transaction_ref UNIQUE (transaction_ref)
);

CREATE TABLE System_Audit_Logs (
    audit_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id   NUMBER,
    event_type      VARCHAR2(80) NOT NULL,
    entity_name     VARCHAR2(80) NOT NULL,
    entity_id       NUMBER,
    event_details   VARCHAR2(4000),
    event_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_system_audit_logs PRIMARY KEY (audit_id)
);

CREATE OR REPLACE PROCEDURE Log_System_Event (
    p_event_type    IN VARCHAR2,
    p_entity_name   IN VARCHAR2,
    p_entity_id     IN NUMBER DEFAULT NULL,
    p_event_details IN VARCHAR2 DEFAULT NULL,
    p_actor_user_id IN NUMBER DEFAULT NULL
) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO System_Audit_Logs (
        actor_user_id, event_type, entity_name, entity_id, event_details
    ) VALUES (
        p_actor_user_id, p_event_type, p_entity_name, p_entity_id, p_event_details
    );

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END Log_System_Event;
/

CREATE OR REPLACE PACKAGE Tourism_Manager_Pkg AS
    PROCEDURE Register_User (
        p_full_name IN Users.full_name%TYPE,
        p_email     IN Users.email%TYPE,
        p_phone     IN Users.phone%TYPE DEFAULT NULL,
        p_role      IN Users.user_role%TYPE DEFAULT 'CUSTOMER',
        p_user_id   OUT Users.user_id%TYPE
    );

    FUNCTION Calculate_Destination_Revenue (
        p_destination_id IN Destinations.destination_id%TYPE
    ) RETURN NUMBER;

    PROCEDURE Batch_Confirm_Pending_Bookings (
        p_limit IN PLS_INTEGER DEFAULT NULL
    );

    FUNCTION Is_Batch_Confirm_Allowed RETURN BOOLEAN;
END Tourism_Manager_Pkg;
/

CREATE OR REPLACE PACKAGE BODY Tourism_Manager_Pkg AS
    g_batch_confirm_authorized BOOLEAN := FALSE;

    PROCEDURE Register_User (
        p_full_name IN Users.full_name%TYPE,
        p_email     IN Users.email%TYPE,
        p_phone     IN Users.phone%TYPE DEFAULT NULL,
        p_role      IN Users.user_role%TYPE DEFAULT 'CUSTOMER',
        p_user_id   OUT Users.user_id%TYPE
    ) IS
        e_invalid_name  EXCEPTION;
        e_invalid_email EXCEPTION;
        e_invalid_role  EXCEPTION;
        l_role Users.user_role%TYPE := UPPER(TRIM(p_role));
    BEGIN
        IF p_full_name IS NULL OR TRIM(p_full_name) IS NULL THEN
            RAISE e_invalid_name;
        END IF;

        IF p_email IS NULL
           OR NOT REGEXP_LIKE(
               TRIM(p_email),
               '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
           )
        THEN
            RAISE e_invalid_email;
        END IF;

        IF l_role NOT IN ('CUSTOMER', 'AGENT', 'ADMIN') THEN
            RAISE e_invalid_role;
        END IF;

        INSERT INTO Users (full_name, email, phone, user_role)
        VALUES (TRIM(p_full_name), LOWER(TRIM(p_email)), p_phone, l_role)
        RETURNING user_id INTO p_user_id;

        Log_System_Event(
            p_event_type => 'USER_REGISTRATION_ATTEMPTED',
            p_entity_name => 'USERS',
            p_entity_id => p_user_id,
            p_event_details => 'Registration recorded; caller controls the main transaction.'
        );
    EXCEPTION
        WHEN e_invalid_name THEN
            RAISE_APPLICATION_ERROR(-20001, 'Full name is required.');
        WHEN e_invalid_email THEN
            RAISE_APPLICATION_ERROR(-20002, 'A valid email address is required.');
        WHEN e_invalid_role THEN
            RAISE_APPLICATION_ERROR(-20003, 'Role must be CUSTOMER, AGENT, or ADMIN.');
        WHEN DUP_VAL_ON_INDEX THEN
            Log_System_Event(
                p_event_type => 'USER_REGISTRATION_REJECTED',
                p_entity_name => 'USERS',
                p_event_details => 'Duplicate email address: ' || SUBSTR(p_email, 1, 200)
            );
            RAISE_APPLICATION_ERROR(-20004, 'A user with this email already exists.');
    END Register_User;

    FUNCTION Calculate_Destination_Revenue (
        p_destination_id IN Destinations.destination_id%TYPE
    ) RETURN NUMBER IS
        l_revenue NUMBER;
    BEGIN
        SELECT NVL(SUM(tp.price * b.travelers_count), 0)
          INTO l_revenue
          FROM Bookings b
          JOIN Travel_Packages tp ON tp.package_id = b.package_id
         WHERE tp.destination_id = p_destination_id
           AND b.status = 'CONFIRMED';

        RETURN l_revenue;
    END Calculate_Destination_Revenue;

    PROCEDURE Batch_Confirm_Pending_Bookings (
        p_limit IN PLS_INTEGER DEFAULT NULL
    ) IS
        CURSOR c_pending IS
            SELECT b.booking_id,
                   b.package_id,
                   b.travelers_count,
                   tp.capacity,
                   NVL((
                       SELECT SUM(confirmed_booking.travelers_count)
                         FROM Bookings confirmed_booking
                        WHERE confirmed_booking.package_id = b.package_id
                          AND confirmed_booking.status = 'CONFIRMED'
                   ), 0) AS confirmed_travelers
              FROM Bookings b
              JOIN Travel_Packages tp ON tp.package_id = b.package_id
             WHERE b.status = 'PENDING'
               AND tp.package_status = 'ACTIVE'
             ORDER BY b.booking_id;

        TYPE t_pending_rows IS TABLE OF c_pending%ROWTYPE;
        TYPE t_package_totals IS TABLE OF NUMBER INDEX BY VARCHAR2(40);
        TYPE t_booking_ids IS TABLE OF Bookings.booking_id%TYPE;

        l_pending_rows       t_pending_rows;
        l_package_totals     t_package_totals;
        l_booking_ids        t_booking_ids := t_booking_ids();
        l_package_key        VARCHAR2(40);
        l_previous_auth      BOOLEAN := g_batch_confirm_authorized;
        l_stop_processing    BOOLEAN := FALSE;
    BEGIN
        IF p_limit IS NOT NULL AND p_limit <= 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Batch limit must be greater than zero.');
        END IF;

        -- Serialize capacity allocation between package-driven confirmation batches.
        FOR locked_package IN (
            SELECT package_id
              FROM Travel_Packages
             ORDER BY package_id
               FOR UPDATE
        ) LOOP
            NULL;
        END LOOP;

        OPEN c_pending;
        LOOP
            FETCH c_pending BULK COLLECT INTO l_pending_rows LIMIT 500;
            EXIT WHEN l_pending_rows.COUNT = 0;

            FOR i IN 1 .. l_pending_rows.COUNT LOOP
                IF p_limit IS NOT NULL AND l_booking_ids.COUNT >= p_limit THEN
                    l_stop_processing := TRUE;
                    EXIT;
                END IF;

                l_package_key := TO_CHAR(l_pending_rows(i).package_id);
                IF NOT l_package_totals.EXISTS(l_package_key) THEN
                    l_package_totals(l_package_key) :=
                        l_pending_rows(i).confirmed_travelers;
                END IF;

                IF l_package_totals(l_package_key)
                   + l_pending_rows(i).travelers_count
                   <= l_pending_rows(i).capacity
                THEN
                    l_booking_ids.EXTEND;
                    l_booking_ids(l_booking_ids.COUNT) := l_pending_rows(i).booking_id;
                    l_package_totals(l_package_key) :=
                        l_package_totals(l_package_key)
                        + l_pending_rows(i).travelers_count;
                END IF;
            END LOOP;

            EXIT WHEN l_stop_processing;
        END LOOP;
        CLOSE c_pending;

        IF l_booking_ids.COUNT > 0 THEN
            BEGIN
                g_batch_confirm_authorized := TRUE;
                FORALL i IN 1 .. l_booking_ids.COUNT
                    UPDATE Bookings
                       SET status = 'CONFIRMED'
                     WHERE booking_id = l_booking_ids(i)
                       AND status = 'PENDING';
                g_batch_confirm_authorized := l_previous_auth;
            EXCEPTION
                WHEN OTHERS THEN
                    g_batch_confirm_authorized := l_previous_auth;
                    RAISE;
            END;
        END IF;

        Log_System_Event(
            p_event_type => 'BOOKING_BATCH_CONFIRM_ATTEMPTED',
            p_entity_name => 'BOOKINGS',
            p_event_details => 'Eligible bookings selected: ' || l_booking_ids.COUNT
        );
    END Batch_Confirm_Pending_Bookings;

    FUNCTION Is_Batch_Confirm_Allowed RETURN BOOLEAN IS
    BEGIN
        RETURN g_batch_confirm_authorized;
    END Is_Batch_Confirm_Allowed;
END Tourism_Manager_Pkg;
/

CREATE OR REPLACE TRIGGER Guard_Booking_Status
    BEFORE UPDATE OF status ON Bookings
    FOR EACH ROW
BEGIN
    IF :OLD.status = 'CONFIRMED' AND :NEW.status <> 'CONFIRMED' THEN
        RAISE_APPLICATION_ERROR(-20006, 'A confirmed booking cannot be changed to another status.');
    END IF;

    IF :OLD.status <> 'CONFIRMED'
       AND :NEW.status = 'CONFIRMED'
       AND NOT Tourism_Manager_Pkg.Is_Batch_Confirm_Allowed
    THEN
        RAISE_APPLICATION_ERROR(
            -20007,
            'Bookings can only be confirmed by Tourism_Manager_Pkg.'
        );
    END IF;
END;
